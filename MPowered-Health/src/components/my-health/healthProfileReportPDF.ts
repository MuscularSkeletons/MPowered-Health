import { HEALTH_PROFILE_REPORT_STYLES } from '@/constants/myhealth/healthProfileStyles';

/** Builds safe printable and shareable versions of My health profile. */
export type ProfileSection = {
  title: string;
  items: [string, string][];
};

export type HealthProfileReport = {
  updatedAt: string;
  sections: ProfileSection[];
};

const escapeHtml = (value: string) =>
  value.replace(/[&<>"']/g, (character) => {
    const entities: Record<string, string> = {
      '&': '&amp;',
      '<': '&lt;',
      '>': '&gt;',
      '"': '&quot;',
      "'": '&#39;',
    };
    return entities[character];
  });

/** Creates the plain-text profile used by native sharing and the browser copy fallback. */
export function healthProfileReportText(report: HealthProfileReport) {
  return [
    'My health profile',
    report.updatedAt ? `Updated ${report.updatedAt}` : 'No completed assessments yet',
    'Latest answers across all five assessment categories.',
    ...report.sections.map((section) =>
      [
        section.title,
        ...section.items.map(([label, value]) => `${label}: ${value || 'Not recorded'}`),
      ].join('\n'),
    ),
  ].join('\n\n');
}

/** Creates an isolated A4 document so app navigation and controls never appear in the PDF. */
export function healthProfileReportHtml(report: HealthProfileReport) {
  return `
    <!doctype html>
    <html lang="en">
        <head>
            <meta charset="utf-8">
            <meta name="viewport" content="width=device-width,initial-scale=1">
            <title>My health profile</title>
                
            <style>
              ${HEALTH_PROFILE_REPORT_STYLES}
            </style>
        </head>

        <body>
            <div class="brand">
                <span class="m">M</span>
                <sup class="powered">Powered</sup>
                <span class="health">Health</span>
            </div>

            <h1>My health profile</h1>
            <div class="meta">${escapeHtml(report.updatedAt ? `Updated ${report.updatedAt}` : 'No completed assessments yet')}</div>
            <p class="intro">Latest answers across all five assessment categories.</p>

            ${report.sections.map((section) =>`
            <section>
                <h2>${escapeHtml(section.title)}</h2>
                <dl>${section.items.map(([label, value]) =>`
                    <div class="row">
                        <dt>${escapeHtml(label)}</dt>
                        <dd>${escapeHtml(value || 'Not recorded')}</dd>
                    </div>`,).join('')}
                </dl>
            </section>`,).join('')}

            <div class="footer">Generated by MPowered Health · For personal health reference only.</div>
        </body>
    </html>
  `;
}
